using System.Globalization; // Подключаем пространство имен для вывода цены через точку (80.50) независимо от настроек ОС.

public record Product(int Id, string Name, decimal Price) //  объявляем публичную модель данных record с именем Product и тремя свойствами:
                                                          //  целое число Id, строка Name и точное дробное число Price (для денег используют decimal).
{
    public override string ToString() //  Говорим компилятору, что хотим перезаписать (override) стандартный метод превращения объекта в текст.
    {
        return $"Product {{ Id = {Id}, Name = {Name}, Price = {Price.ToString("F2", CultureInfo.InvariantCulture)} }}"; // возвращаем красиво отформатированную строку.
                                                                                                                        // Двойные фигурные скобки {{ и }} нужны, чтобы
                                                                                                                        // вывести в консоль обычные скобки { и } внутри
                                                                                                                        // интерполированной строки ($).
                                                                                                                        // "F2" заставляет цену всегда показывать
                                                                                                                        // 2 знака после точки (например, 40.00).
    }
}

public class Inventory // Объявляем публичный класс Inventory, который будет управлять складом.
{
    private readonly List<Product> _products = new(); // создаем список товаров. private запрещает доступ к списку извне (инкапсуляция).
                                                      // readonly запрещает перезаписывать саму переменную _products новым списком.
                                                      // new() — сокращенная запись создания пустого списка.

    public void AddProduct(Product product) // Объявляем публичный метод AddProduct, который ничего не возвращает (void), но принимает объект Product.
    {
        _products.Add(product); // Добавляем переданный товар в наш скрытый список.
        Console.WriteLine($"Добавлен продукт: {product}"); // Выводим в консоль сообщение. При подстановке {product} автоматически вызывается наш метод ToString() из 6-й строки.
    }

    public Product? FindProductById(int id) // Объявляем публичный метод поиска, принимающий id.
                                            // Знак ? после Product предупреждает программу, что метод может вернуть пустоту (null), если товар не найден.
    {
        foreach (var product in _products) // Запускаем цикл, который по очереди берет каждый товар из списка _products и кладет во временную переменную product.
        {
            if (product.Id == id) // Проверяем, совпадает ли артикул текущего товара из списка с тем id, который мы ищем.
            {
                return product; // Если совпало, немедленно прекращаем работу метода и возвращаем найденный товар.
            }
        }

        return null; // Эта строчка сработает только если цикл прошел по всем товарам и ни разу не зашел в if. Возвращаем null (ничего не найдено).
    }
}