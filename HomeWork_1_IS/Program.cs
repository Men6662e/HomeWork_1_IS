Console.WriteLine("--- Управление инвентарём ---"); // Заголовок первого блока печатаем в консоль
var inventory  = new Inventory(); // Создаем в памяти новый экземпляр склада и сохраняем ссылку на него в переменную inventory.

inventory.AddProduct(new Product(1, "Молоко", 80.50m)); // создаем объект «Молоко» и сразу передаем его в метод добавления на склад.
                                                        // Буква m в конце числа обязательна — так в C# обозначается денежный тип decimal
inventory.AddProduct(new Product(2, "Хлеб", 40.00m)); // Создаем и добавляем на склад «Хлеб».
inventory.AddProduct(new Product(3, "Сыр", 450.99m)); // Создаем и добавляем на склад «Сыр».

Console.WriteLine("\n--- Поиск товара с ID 2 ---"); // Печатаем заголовок поиска. Символ \n в начале делает отступ в одну пустую строку в консоли.
Product? foundProduct = inventory.FindProductById(2); // Вызываем метод поиска для ID 2 и сохраняем результат в переменную foundProduct (она тоже с ?, так как может принять null).
if (foundProduct is not null) // Проверяем: вернулся ли реальный товар (то есть переменная НЕ пустая).{
{
    Console.WriteLine($"Найден товар: {foundProduct}"); // Выводим информацию о найденном товаре.
}
else // ключевое слово «иначе» (сработает, если условие в строке 11 оказалось ложным, то есть вернулся null).
{
    Console.WriteLine("Товар с ID 2 не найден"); // Выводим сообщение об отсутствии товара.
}

Console.WriteLine("\n--- Поиск товара с ID 99 ---"); // Печатаем заголовок для второго поиска с пустой строкой сверху (\n).
Product? missingProduct = inventory.FindProductById(99); // Ищем товар с ID 99. Так как его нет, метод вернет null в переменную missingProduct.
if (missingProduct is not null) // Проверяем, не пустая ли переменная missingProduct.
{
    Console.WriteLine($"Найден товар: {missingProduct}"); // Эта строка пропустится, так как переменная равна null.
}
else
{
    Console.WriteLine("Товар с ID 99 не найден"); // Выводим в консоль сообщение, что товар с ID 99 не найден.
}
